import React from 'react';
import { useAppStore } from '@/stores/app-store';
import { SettingsSection } from '../components/SettingsSection';
import { SettingsRow } from '../components/SettingsRow';
import { SettingsToggle } from '../components/SettingsToggle';
import { SettingsSelect } from '../components/SettingsSelect';
import { SettingsSegmentedControl } from '../components/SettingsSegmentedControl';

export const GeneralSettings: React.FC = () => {
  const {
    settings,
    updateSetting,
    effort,
    setEffort,
    approvalMode,
    setApprovalMode,
  } = useAppStore();

  const restoreWorkspace = (settings.restoreWorkspaceOnLaunch as boolean) ?? true;
  const confirmExit = (settings.confirmOnExit as boolean) ?? false;
  const streamResponses = (settings.streamResponses as boolean) ?? true;
  const chatSubmitKey = (settings.chatSubmitKey as string) ?? 'enter';
  const fontSize = (settings.fontSize as string) || '14';
  const codeFontFamily = (settings.codeFontFamily as string) || 'JetBrains Mono';
  const diffStyle = (settings.diffStyle as string) || 'split';
  const autoSaveMemory = (settings.autoSaveMemory as boolean) ?? true;
  const defaultShell = (settings.defaultShell as string) || 'powershell.exe';
  const scrollback = (settings.terminalScrollback as string) || '5000';

  return (
    <div className="space-y-6">
      {/* Group 1: Application */}
      <SettingsSection
        title="Application"
        description="Startup behavior and window lifecycle preferences."
      >
        <SettingsRow
          label="Restore Last Workspace"
          description="Automatically reopen the previously active workspace when Refx launches."
        >
          <SettingsToggle
            checked={restoreWorkspace}
            onChange={(val) => updateSetting('restoreWorkspaceOnLaunch', val)}
            ariaLabel="Restore last workspace"
          />
        </SettingsRow>

        <SettingsRow
          label="Confirm Before Closing"
          description="Display a confirmation prompt before quitting when background agent processes are running."
        >
          <SettingsToggle
            checked={confirmExit}
            onChange={(val) => updateSetting('confirmOnExit', val)}
            ariaLabel="Confirm before closing"
          />
        </SettingsRow>
      </SettingsSection>

      {/* Group 2: Chat & AI */}
      <SettingsSection
        title="Chat & AI Execution"
        description="Inference response generation and input preferences."
      >
        <SettingsRow
          label="Reasoning Effort"
          description="Default thinking budget allocation for supported reasoning models."
        >
          <SettingsSelect
            value={effort || 'Auto'}
            onChange={(v) => {
              setEffort(v);
              updateSetting('effort', v);
            }}
            options={[
              { value: 'Auto', label: 'Auto (Recommended)' },
              { value: 'Low', label: 'Low · Fast' },
              { value: 'Medium', label: 'Medium · Balanced' },
              { value: 'High', label: 'High · Deep Reasoning' },
              { value: 'Max', label: 'Max · Maximum Budget' },
            ]}
          />
        </SettingsRow>

        <SettingsRow
          label="Stream Responses"
          description="Stream model tokens in real time as they are generated by the active provider."
        >
          <SettingsToggle
            checked={streamResponses}
            onChange={(val) => updateSetting('streamResponses', val)}
            ariaLabel="Stream responses"
          />
        </SettingsRow>

        <SettingsRow
          label="Send Message Shortcut"
          description="Keyboard shortcut to submit prompts in the chat composer."
        >
          <SettingsSegmentedControl
            value={chatSubmitKey}
            onChange={(val) => updateSetting('chatSubmitKey', val)}
            options={[
              { id: 'enter', label: 'Enter' },
              { id: 'cmd_enter', label: 'Ctrl + Enter' },
            ]}
          />
        </SettingsRow>
      </SettingsSection>

      {/* Group 3: Editor & Diffs */}
      <SettingsSection
        title="Editor & Diffs"
        description="Code presentation, typography, and file modification reviews."
      >
        <SettingsRow
          label="Editor Font Size"
          description="Font size applied to code blocks, file inspections, and diff editors."
        >
          <SettingsSelect
            value={fontSize}
            onChange={(v) => updateSetting('fontSize', v)}
            options={[
              { value: '12', label: '12px · Compact' },
              { value: '13', label: '13px · Small' },
              { value: '14', label: '14px · Standard' },
              { value: '15', label: '15px · Medium' },
              { value: '16', label: '16px · Large' },
            ]}
          />
        </SettingsRow>

        <SettingsRow
          label="Monospace Font Family"
          description="Primary font family for rendered code fences, syntax trees, and diffs."
        >
          <SettingsSelect
            value={codeFontFamily}
            onChange={(v) => updateSetting('codeFontFamily', v)}
            options={[
              { value: 'JetBrains Mono', label: 'JetBrains Mono' },
              { value: 'Fira Code', label: 'Fira Code' },
              { value: 'Cascadia Code', label: 'Cascadia Code' },
              { value: 'Consolas', label: 'Consolas' },
            ]}
          />
        </SettingsRow>

        <SettingsRow
          label="Diff Presentation Mode"
          description="Preferred visualization for reviewing pending file modifications."
        >
          <SettingsSegmentedControl
            value={diffStyle}
            onChange={(val) => updateSetting('diffStyle', val)}
            options={[
              { id: 'split', label: 'Side-by-Side Split' },
              { id: 'unified', label: 'Unified Inline' },
            ]}
          />
        </SettingsRow>
      </SettingsSection>

      {/* Group 4: Automation */}
      <SettingsSection
        title="Automation & Permissions"
        description="Autonomous workflow execution policies and memory capture."
      >
        <SettingsRow
          label="Automatic Memory Capture"
          description="Continuously summarize and store important context, instructions, and preferences during conversations."
        >
          <SettingsToggle
            checked={autoSaveMemory}
            onChange={(val) => updateSetting('autoSaveMemory', val)}
            ariaLabel="Automatic memory capture"
          />
        </SettingsRow>

        <SettingsRow
          label="Default Approval Mode"
          description="Execution policy governing autonomous file changes and terminal commands."
        >
          <SettingsSelect
            value={approvalMode}
            onChange={(v) => {
              setApprovalMode(v as any);
              updateSetting('approvalMode', v);
            }}
            options={[
              { value: 'ask', label: 'Ask Approval (Safe)' },
              { value: 'auto_preview', label: 'Auto Preview Diffs' },
              { value: 'turbo', label: 'Turbo (Unrestricted)' },
            ]}
          />
        </SettingsRow>
      </SettingsSection>

      {/* Group 5: Terminal */}
      <SettingsSection
        title="Terminal"
        description="Integrated pseudo-terminal defaults and scrollback limits."
      >
        <SettingsRow
          label="Default Shell"
          description="Windows command interpreter launched in the interactive terminal panel."
        >
          <SettingsSelect
            value={defaultShell}
            onChange={(v) => updateSetting('defaultShell', v)}
            options={[
              { value: 'powershell.exe', label: 'PowerShell (powershell.exe)' },
              { value: 'cmd.exe', label: 'Command Prompt (cmd.exe)' },
              { value: 'bash.exe', label: 'Git Bash (bash.exe)' },
            ]}
          />
        </SettingsRow>

        <SettingsRow
          label="Scrollback Buffer Limit"
          description="Maximum lines retained in memory per interactive terminal session."
        >
          <SettingsSelect
            value={scrollback}
            onChange={(v) => updateSetting('terminalScrollback', v)}
            options={[
              { value: '1000', label: '1,000 lines' },
              { value: '2500', label: '2,500 lines' },
              { value: '5000', label: '5,000 lines (Default)' },
              { value: '10000', label: '10,000 lines' },
            ]}
          />
        </SettingsRow>
      </SettingsSection>
    </div>
  );
};
